function event(
  id: string,
  offsetDays: number,
  actor: string,
  role: AuditEvent["role"],
  action: string,
  entity: AuditEvent["entity"],
  entityId: string,
  detail: string,
): AuditEvent {
  return {
    id,
    at: iso(offsetDays, 11, 30),
    actor,
    role,
    action,
    entity,
    entityId,
    detail,
  };
}

